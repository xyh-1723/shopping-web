import java.sql.*;
import java.util.*;

public class SqlDialectProbe {

    record Target(String name, String url, String user, String pass) {}

    public static void main(String[] args) throws Exception {
        List<Target> targets = new ArrayList<>();
        targets.add(new Target("H2", "jdbc:h2:mem:probe;DB_CLOSE_DELAY=-1", "sa", ""));
        targets.add(new Target("MySQL", "jdbc:mysql://127.0.0.1:3306/mall?useSSL=false&allowPublicKeyRetrieval=true&serverTimezone=UTC", "root", "123456"));

        for (Target t : targets) {
            System.out.println("\n================ " + t.name() + " ================");
            try (Connection c = DriverManager.getConnection(t.url(), t.user(), t.pass())) {
                drop(c, "probe_t");
                drop(c, "probe_id");

                // ---- DDL: auto increment id ----
                ddl(c, "AUTO_INCREMENT",
                        "CREATE TABLE probe_id (id BIGINT AUTO_INCREMENT PRIMARY KEY, v VARCHAR(10))");
                ddl(c, "IDENTITY",
                        "CREATE TABLE probe_id2 (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v VARCHAR(10))");

                // ---- base table ----
                try (Statement s = c.createStatement()) {
                    s.execute("CREATE TABLE probe_t (id BIGINT PRIMARY KEY, ts TIMESTAMP, content VARCHAR(50))");
                    s.execute("INSERT INTO probe_t VALUES (1, TIMESTAMP '2026-01-01 10:00:00', 'x')");
                } catch (SQLException e) {
                    System.out.println("  [setup] FAIL " + e.getMessage().split("\n")[0]);
                }

                // ---- date arithmetic candidates ----
                q(c, "ts + INTERVAL 15 MINUTE", "SELECT ts + INTERVAL 15 MINUTE AS r FROM probe_t");
                q(c, "INTERVAL '15' MINUTE   ", "SELECT ts + INTERVAL '15' MINUTE AS r FROM probe_t");
                q(c, "DATEADD                ", "SELECT DATEADD('MINUTE', 15, ts) AS r FROM probe_t");
                q(c, "DATE_ADD               ", "SELECT DATE_ADD(ts, INTERVAL 15 MINUTE) AS r FROM probe_t");
                q(c, "TIMESTAMPADD           ", "SELECT TIMESTAMPADD(MINUTE, 15, ts) AS r FROM probe_t");
                q(c, "TIMESTAMPADD SQL_TSI   ", "SELECT TIMESTAMPADD(SQL_TSI_MINUTE, 15, ts) AS r FROM probe_t");

                // ---- ALTER COLUMN variants ----
                ddl(c, "MODIFY COLUMN        ", "ALTER TABLE probe_t MODIFY COLUMN content VARCHAR(500) NOT NULL");
                ddl(c, "ALTER COLUMN SET TYPE", "ALTER TABLE probe_t ALTER COLUMN content SET DATA TYPE VARCHAR(400)");

                // ---- locking ----
                q(c, "FOR UPDATE            ", "SELECT id FROM probe_t WHERE id = 1 FOR UPDATE");
                q(c, "FOR UPDATE SKIP LOCKED", "SELECT id FROM probe_t WHERE id = 1 FOR UPDATE SKIP LOCKED");

                drop(c, "probe_t");
                drop(c, "probe_id");
                drop(c, "probe_id2");
            } catch (SQLException e) {
                System.out.println("  CONNECT FAIL " + e.getMessage().split("\n")[0]);
            }
        }
    }

    static void drop(Connection c, String t) {
        try (Statement s = c.createStatement()) {
            s.execute("DROP TABLE IF EXISTS " + t);
        } catch (SQLException ignored) {
        }
    }

    static void ddl(Connection c, String label, String sql) {
        try (Statement s = c.createStatement()) {
            s.execute(sql);
            System.out.println("  OK   " + label + " :: " + sql);
        } catch (SQLException e) {
            System.out.println("  FAIL " + label + " :: " + firstLine(e));
        }
    }

    static void q(Connection c, String label, String sql) {
        try (Statement s = c.createStatement(); ResultSet rs = s.executeQuery(sql)) {
            String v = rs.next() ? String.valueOf(rs.getObject(1)) : "(no rows)";
            System.out.println("  OK   " + label + " => " + v);
        } catch (SQLException e) {
            System.out.println("  FAIL " + label + " :: " + firstLine(e));
        }
    }

    static String firstLine(SQLException e) {
        String m = e.getMessage();
        if (m == null) return e.getClass().getSimpleName();
        return m.split("\n")[0].replace("\r", "");
    }
}
