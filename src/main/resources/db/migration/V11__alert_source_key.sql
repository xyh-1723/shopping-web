-- 提醒的幂等键：同一件事只提醒一次。
--
-- 弃单召回需要它：订单超时关闭后要提醒用户「东西还在」，而关单扫描可能重复扫到
-- （例如上一轮归还库存失败、下一轮重试），同一个订单不能因此提醒两次。
-- 之前的提醒靠「业务状态」天然幂等（基线价格被重置、到货标记被改写），
-- 但「这笔订单已经召回了」这件事没有地方记——source_key 就是记它的地方。
--
-- 用唯一索引而不是「先查再插」：查与插之间的那一瞬间，另一个事务可以插进来，
-- 于是两条提醒同时诞生。让数据库来拒绝，是唯一靠得住的顺序保证。

ALTER TABLE mall_alert ADD COLUMN source_key VARCHAR(64);

-- NULL 不参与唯一性判断（实测 H2 允许多行 NULL），所以既有的降价/到货/推荐提醒
-- 不受影响——只有显式带了来源键的提醒才享受「同一来源只一条」的约束。
CREATE UNIQUE INDEX uq_alert_source ON mall_alert(username, source_key);
