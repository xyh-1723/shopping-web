-- 主动服务扫描的公平性与克制。
--
-- 背景：扫描原本是「取排序最靠前的 N 条关注来处理」。这在关注总数 ≤ N 时完全正确，
-- 一旦超过 N，排在最末尾的那批关注就永远进不了扫描窗口——它们降价了也没人被告知，
-- 而且没人会注意到这件事：日志只报「扫描了 500 条」，看起来一切正常。
-- 这类缺陷的共同点是「规模小的时候看不出来，规模大到超出窗口时才开始咬人」，
-- 而且它安静得可怕：日志照常报「扫描了 N 条」，没有任何一处会变红。
--
-- 修法不是把 N 调大（那只是在推迟问题登场），而是给扫描一个游标：
-- 每条关注记「我上次是什么时候被扫的」，扫描按「最久没被照顾」排序，处理完推进游标。
-- 于是 N 不再是「能服务多少用户」的上限，而退化成它本来的含义——
-- 「每次处理多少条」，所有关注最终都会被轮到。

ALTER TABLE mall_product_watch ADD COLUMN last_scanned_at TIMESTAMP;

-- 支持「按最久未扫描排序」的扫描查询。没有索引时，这张表一长，
-- 每次轮询都要全表排序一次——轮询是最频繁的操作，不能让它退化。
CREATE INDEX idx_watch_scan ON mall_product_watch(last_scanned_at);
