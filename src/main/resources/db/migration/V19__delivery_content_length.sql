-- V19：notification_delivery.content 的长度对齐到 notification.content。
--
-- 依赖：V17（notification_delivery 表已存在）。编号必须 > 18 且一次写对：
-- Flyway 默认禁止 out-of-order，V17 / V18 已落盘并带校验和，
-- 所以这里新开一个文件，而不是回头改 V17——改已落盘的迁移会让既有环境的
-- checksum 校验失败（上线即崩，而不是上线即生效）。V17 一个字都没动。
--
-- ===================================================================
-- 为什么要对齐：长度不对称会造出「半成功」
-- ===================================================================
-- V1 里 notification.content 是 VARCHAR(500)；V17 里 notification_delivery.content
-- 是 VARCHAR(400)。而 NotificationSink.deliver 是「先写站内信、再写留痕」两步：
-- 文案一旦超过 400，第一步成功、第二步失败，于是形成
--   「用户收到了通知，但投递记录没有」的半成功。
-- 更糟的是它不红也不报错——失败被 outbox 的重试吸收，事件滚几轮后变成死信，
-- 症状出现在别处（「这条通知怎么没有留痕」），排查成本远高于现在改一行。
--
-- 为什么现在改而不是等它触发：现在所有事件文案都 < 100 字符，改动的半径是
-- 「一个 ALTER」；等它触发时的半径是「线上有一批半成功的行要补」。
-- 这类「将来会变成一个症状诡异的问题」的隐患，正是本项目最忌讳的一类。
--
-- ⚠ 不变量：两张表的 content 长度必须相等。
--   V19MigrationTest 断言的是「相等」而不是「都等于 500」——写死 500 会在将来
--   又一次单边改动时失效（两侧一起改成 600 会让它假红），而「相等」守住的
--   是这个不变量本身：留痕必须接得住站内信接得住的任何一条文案。

-- 同 V13：MySQL 只有 MODIFY，且必须重复完整类型。NOT NULL 一并写上——
-- MODIFY 是整体替换列定义，漏掉它就会把 V17 的 NOT NULL 悄悄改成可空。
ALTER TABLE notification_delivery MODIFY COLUMN content VARCHAR(500) NOT NULL;
